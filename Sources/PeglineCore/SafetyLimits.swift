import Foundation

/// Limits for image data Pegline did not create itself (clipboard contents, copied files).
/// They keep a huge or hostile image from exhausting memory when it is decoded.
public enum ImageLimits {
    /// Larger files or clipboard payloads are not decoded or copied.
    public static let maxBytes: Int64 = 300 * 1024 * 1024
    /// About 250 megapixels: far above any multi-display screenshot (three 6K displays ≈ 60 MP).
    public static let maxPixels: Int64 = 250_000_000

    public static func allows(bytes: Int64) -> Bool { bytes >= 0 && bytes <= maxBytes }

    public static func allows(width: Int, height: Int) -> Bool {
        guard width > 0, height > 0 else { return false }
        return Int64(width) * Int64(height) <= maxPixels
    }
}

/// Clipboard markers from the nspasteboard.org convention. Password managers and similar apps set
/// them on secrets or short-lived data; clipboard tools are expected to ignore such contents.
public enum ClipboardPrivacy {
    public static let markers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type"
    ]

    /// True if any item carries a "do not record" marker.
    public static func isPrivate(items: [[String]]) -> Bool {
        items.contains { types in types.contains { markers.contains($0) } }
    }
}
